CREATE OR REPLACE FUNCTION public.te_refresh_apartado_product_flags(p_product_ids bigint[])
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
BEGIN
  IF COALESCE(array_length(p_product_ids, 1), 0) = 0 THEN
    RETURN;
  END IF;

  WITH reserved AS (
    SELECT d.product_id, SUM(d.required_qty)::bigint AS reserved_qty
    FROM public.sales s
    CROSS JOIN LATERAL public.te_inventory_demand(s.items) d
    WHERE s.origin_type = 'apartado'
      AND s.status = 'activo'
      AND s.cancelled_at IS NULL
      AND NOT s.se_lo_llevo
      AND d.product_id = ANY(p_product_ids)
    GROUP BY d.product_id
  )
  UPDATE public.products p
  SET
    is_apartado = CASE
      WHEN COALESCE(p.is_archived, false) THEN false
      ELSE (COALESCE(p.stock, 0) <= 0 AND COALESCE(r.reserved_qty, 0) > 0)
    END,
    out_of_stock = CASE
      WHEN COALESCE(p.is_archived, false) THEN true
      WHEN COALESCE(p.stock, 0) <= 0 THEN COALESCE(r.reserved_qty, 0) = 0
      ELSE false
    END,
    -- La disponibilidad se controla con out_of_stock/is_apartado. No destruye
    -- la preferencia editorial is_published al agotarse, para que una
    -- cancelacion pueda restaurar visibilidad sin publicar borradores ocultos.
    is_published = CASE
      WHEN COALESCE(p.is_archived, false) THEN false
      ELSE p.is_published
    END
  FROM (SELECT unnest(p_product_ids) AS product_id) ids
  LEFT JOIN reserved r ON r.product_id = ids.product_id
  WHERE p.id = ids.product_id;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.te_refund_credit(p_request_id uuid, p_sale_id bigint, p_override_tickets uuid[] DEFAULT NULL::uuid[])
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_operation constant text := 'refund_credit';
  v_cached jsonb;
  v_response jsonb;
  v_sale public.sales%ROWTYPE;
  v_entries jsonb;
  v_amount numeric;
  v_used_permission text;
  v_authorized_by text;
  v_customer text;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'No autenticado';
  END IF;
  v_used_permission := CASE WHEN public.te_permission_or_override('canEditApartado', p_override_tickets)
                             THEN 'canEditApartado' ELSE 'canCancelSale' END;
  IF NOT public.te_permission_or_override(v_used_permission, p_override_tickets) THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Sin permiso para devolver saldos a favor';
  END IF;

  v_cached := public.te_rpc_replay(p_request_id, v_operation);
  IF v_cached IS NOT NULL THEN RETURN v_cached; END IF;
  -- Sale dinero del cajón: exige caja abierta de quien lo entrega.
  PERFORM public.te_assert_open_shift();

  IF NOT public.te_has_permission(v_used_permission) THEN
    v_authorized_by := public.te_consume_matching_override(v_used_permission, p_override_tickets);
    IF v_authorized_by IS NULL THEN
      RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'Autorización inválida o expirada';
    END IF;
  END IF;
  PERFORM set_config('sunnypos.rpc_v2', 'on', true);

  SELECT * INTO v_sale FROM public.sales WHERE id = p_sale_id FOR UPDATE;
  IF NOT FOUND OR v_sale.status <> 'cancelado' OR COALESCE(v_sale.saldo_favor, 0) <= 0 THEN
    RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'Este apartado no tiene saldo a favor';
  END IF;

  v_entries := public.te_refund_sale_balance(p_sale_id, p_request_id, 'rpc_credit_refund', 'Saldo a favor devuelto', now());
  SELECT round(COALESCE(SUM(abs((e ->> 'amount')::numeric)), 0), 2) INTO v_amount FROM jsonb_array_elements(v_entries) e;

  UPDATE public.sales
     SET saldo_favor = 0, paid_amount = 0, last_payment_at = now(), updated_at = now(), version = version + 1
   WHERE id = p_sale_id;

  v_customer := COALESCE(NULLIF(split_part(v_sale.customer, ' · ', 1), ''), 'cliente');
  PERFORM public.te_log_activity(
    'apartado_reembolso',
    format('Devolvió a %s su saldo a favor — $%s', v_customer, v_amount),
    jsonb_build_object('id', p_sale_id, 'customer', v_customer, 'refund', v_amount, 'refunds', v_entries,
                       'saldo_favor', true, 'authorized_by', v_authorized_by, 'request_id', p_request_id)
  );

  v_response := jsonb_build_object('ok', true, 'operation', v_operation, 'request_id', p_request_id,
    'refund_amount', v_amount, 'refunds', v_entries,
    'sale', jsonb_build_object('id', p_sale_id, 'saldo_favor', 0, 'version', v_sale.version + 1));
  PERFORM public.te_rpc_store(p_request_id, v_operation, p_sale_id, v_response);
  RETURN v_response;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.te_refund_sale_balance(p_sale_id bigint, p_request_id uuid, p_source text, p_reason text, p_paid_at timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_total_remaining numeric;
  v_take            numeric;
  v_line            smallint := 0;
  v_method          record;
  v_refunds         jsonb := '[]'::jsonb;
  v_entry           jsonb;
  v_actor_email     text := lower(auth.jwt() ->> 'email');
  v_is_libreta      boolean;
  v_paper           boolean;
BEGIN
  SELECT public.te_sale_is_libreta(items) INTO v_is_libreta FROM public.sales WHERE id = p_sale_id;
  SELECT round(GREATEST(COALESCE(SUM(amount), 0), 0), 2)
    INTO v_total_remaining
  FROM public.sale_payments
  WHERE sale_id = p_sale_id;

  IF v_total_remaining <= 0 THEN
    RETURN v_refunds;
  END IF;

  FOR v_method IN
    SELECT method, round(SUM(amount), 2) AS balance
    FROM public.sale_payments
    WHERE sale_id = p_sale_id
    GROUP BY method
    HAVING round(SUM(amount), 2) > 0
    ORDER BY CASE method WHEN 'efectivo' THEN 1 WHEN 'transferencia' THEN 2 ELSE 3 END
  LOOP
    EXIT WHEN v_total_remaining <= 0;
    v_take := LEAST(v_method.balance, v_total_remaining);
    IF v_take <= 0 THEN CONTINUE; END IF;
    v_line := v_line + 1;
    -- Dinero de papel (abonos de libreta, método desconocido): su devolución
    -- tampoco lleva fecha de cobro, así no resta en Reportes ni en el corte
    -- lo que nunca sumó. El instante real queda en meta.devuelto_en.
    v_paper := COALESCE(v_is_libreta, false) AND v_method.method = 'unknown';

    v_entry := jsonb_build_object(
      'amount', -v_take,
      'method', v_method.method,
      'date', p_paid_at,
      'request_id', p_request_id,
      'request_line', v_line,
      'collected_by', v_actor_email,
      'kind', 'refund',
      'reason', NULLIF(btrim(p_reason), '')
    );

    INSERT INTO public.sale_payments (
      sale_id, request_id, request_line, kind, amount, method, paid_at,
      collected_by, collected_by_email, is_estimated, source, meta
    ) VALUES (
      p_sale_id, p_request_id, v_line, 'refund', -v_take, v_method.method,
      CASE WHEN v_paper THEN NULL ELSE p_paid_at END,
      auth.uid(), v_actor_email, v_method.method = 'unknown', p_source,
      jsonb_build_object('reason', NULLIF(btrim(p_reason), ''))
        || CASE WHEN v_paper THEN jsonb_build_object('devuelto_en', p_paid_at, 'libreta', true) ELSE '{}'::jsonb END
    );

    v_refunds := v_refunds || jsonb_build_array(v_entry);
    v_total_remaining := round(v_total_remaining - v_take, 2);
  END LOOP;

  IF v_total_remaining > 0 THEN
    RAISE EXCEPTION USING
      ERRCODE = 'P0001',
      MESSAGE = 'No se pudo distribuir completamente la devolucion por metodo original';
  END IF;

  RETURN v_refunds;
END;
$function$
;

CREATE OR REPLACE FUNCTION public.te_request_override(p_permission text, p_authorizer_email text, p_pin text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public', 'extensions'
AS $function$
DECLARE
  v_actor_uid      uuid := auth.uid();
  v_actor_email    text := lower(auth.jwt() ->> 'email');
  v_email          text := lower(btrim(p_authorizer_email));
  v_authorizer_uid uuid;
  v_hash           text;
  v_recent_fails   integer;
  v_target_fails   integer;
  v_ticket         uuid;
  v_expires_at     timestamptz;
BEGIN
  IF v_actor_uid IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = '42501', MESSAGE = 'No autenticado';
  END IF;

  -- Los fallos NO hacen RAISE: una excepción revertiría el registro del
  -- intento y el contador de abajo nunca subiría.

  -- Freno por quien pide: 5 fallos en 10 min.
  SELECT count(*) INTO v_recent_fails
  FROM public.activity_log
  WHERE action = 'override_fallido'
    AND user_email = v_actor_email
    AND created_at > now() - interval '10 minutes';
  IF v_recent_fails >= 5 THEN
    RETURN jsonb_build_object('ok', false, 'message', 'Demasiados intentos — espera unos minutos');
  END IF;

  -- Freno por autorizador (aunque se turnen varias cuentas): 10 fallos en 1 h.
  SELECT count(*) INTO v_target_fails
  FROM public.activity_log
  WHERE action = 'override_fallido'
    AND meta ->> 'attempted_authorizer' = v_email
    AND created_at > now() - interval '1 hour';
  IF v_target_fails >= 10 THEN
    RETURN jsonb_build_object('ok', false, 'message', 'El PIN de esa persona está bloqueado por intentos fallidos — espera una hora');
  END IF;

  SELECT u.id INTO v_authorizer_uid FROM auth.users u WHERE lower(u.email) = v_email;
  SELECT pin_hash INTO v_hash FROM public.user_pins WHERE email = v_email;

  IF v_authorizer_uid IS NULL OR v_hash IS NULL OR crypt(p_pin, v_hash) <> v_hash THEN
    PERFORM public.te_log_activity(
      'override_fallido',
      format('Intento de autorizacion fallido para "%s" (autorizador: %s)', p_permission, COALESCE(v_email, 'desconocido')),
      jsonb_build_object('permission', p_permission, 'attempted_authorizer', v_email)
    );
    RETURN jsonb_build_object('ok', false, 'message', 'PIN o autorización inválida');
  END IF;

  IF NOT public._te_permission_for_email(v_email, p_permission) THEN
    PERFORM public.te_log_activity(
      'override_fallido',
      format('%s no tiene el permiso "%s" para autorizar', v_email, p_permission),
      jsonb_build_object('permission', p_permission, 'attempted_authorizer', v_email)
    );
    RETURN jsonb_build_object('ok', false, 'message', 'Esa persona tampoco tiene ese permiso');
  END IF;

  INSERT INTO public.permission_overrides (permission, granted_to_uid, granted_by_email, expires_at)
  VALUES (p_permission, v_actor_uid, v_email, now() + interval '5 minutes')
  RETURNING id, expires_at INTO v_ticket, v_expires_at;

  PERFORM public.te_log_activity(
    'permiso_autorizado',
    format('%s autorizó "%s" a %s', v_email, p_permission, v_actor_email),
    jsonb_build_object('permission', p_permission, 'authorized_by', v_email, 'authorized_for', v_actor_email)
  );

  RETURN jsonb_build_object('ok', true, 'ticket', v_ticket, 'expires_at', v_expires_at);
END;
$function$
;

