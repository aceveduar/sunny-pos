CREATE OR REPLACE FUNCTION public.te_rpc_replay(p_request_id uuid, p_operation text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'public'
AS $function$
DECLARE
  v_row public.pos_rpc_requests%ROWTYPE;
BEGIN
