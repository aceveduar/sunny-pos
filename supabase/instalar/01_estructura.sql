CREATE OR REPLACE FUNCTION public.te_log_client_error(p_module text, p_message text, p_source text DEFAULT NULL::text, p_stack text DEFAULT NULL::text, p_url text DEFAULT NULL::text, p_user_agent text DEFAULT NULL::text)
