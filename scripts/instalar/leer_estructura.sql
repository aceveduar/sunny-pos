-- Solo lectura: genera el DDL de public (sin datos). Columnas: ord, obj, stmt.
with
tbl as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r'
),
fn as (
  select p.oid, p.proname, pg_get_function_identity_arguments(p.oid) args, p.prokind
  from pg_proc p join pg_namespace n on n.oid=p.pronamespace
  where n.nspname='public'
    and not exists (select 1 from pg_depend d where d.objid=p.oid and d.deptype='e')
)
-- 10 secuencias
select 10 ord, s.sequencename::text obj,
  format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s;',
    s.sequencename, s.data_type, s.start_value, s.increment_by, s.min_value, s.max_value, s.cache_size,
    case when s.cycle then ' CYCLE' else '' end) stmt
from pg_sequences s where s.schemaname='public'
union all
-- 20 tablas con columnas
select 20, t.relname, format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
  string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
    case when a.attidentity='a' then ' GENERATED ALWAYS AS IDENTITY'
         when a.attidentity='d' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end,
    case when a.attgenerated='s' then ' GENERATED ALWAYS AS (' || pg_get_expr(ad.adbin, ad.adrelid) || ') STORED'
         when ad.adbin is not null and a.attidentity='' then ' DEFAULT ' || pg_get_expr(ad.adbin, ad.adrelid) else '' end,
    case when a.attnotnull then ' NOT NULL' else '' end), E',\n' order by a.attnum))
from tbl t join pg_attribute a on a.attrelid=t.oid and a.attnum>0 and not a.attisdropped
left join pg_attrdef ad on ad.adrelid=t.oid and ad.adnum=a.attnum
group by t.relname
union all
-- 25 secuencias ligadas a columnas
select 25, s.relname, format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, t.relname, a.attname)
from pg_depend d join pg_class s on s.oid=d.objid and s.relkind='S'
join tbl t on t.oid=d.refobjid join pg_attribute a on a.attrelid=t.oid and a.attnum=d.refobjsubid
where d.deptype='a'
union all
-- 30 PK/UNIQUE/CHECK/EXCLUDE · 40 FK
select case when co.contype='f' then 40 else 30 end, t.relname || '.' || co.conname,
  format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
from pg_constraint co join tbl t on t.oid=co.conrelid
where co.contype in ('p','u','c','x','f')
union all
-- 50 funciones
select 50, f.proname || '(' || f.args || ')', pg_get_functiondef(f.oid) || ';'
from fn f where f.prokind in ('f','p')
union all
-- 60 índices que no vienen de una restricción
select 60, i.relname, pg_get_indexdef(i.oid) || ';'
from pg_index x join pg_class i on i.oid=x.indexrelid join tbl t on t.oid=x.indrelid
where not exists (select 1 from pg_constraint co where co.conindid=x.indexrelid)
union all
-- 70 triggers
select 70, t.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
from pg_trigger tg join tbl t on t.oid=tg.tgrelid where not tg.tgisinternal
union all
-- 80 RLS
select 80, c.relname, format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', c.relname)
  || case when c.relforcerowsecurity then format(' ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', c.relname) else '' end
from pg_class c join tbl t on t.oid=c.oid where c.relrowsecurity
union all
-- 85 políticas
select 85, p.tablename || '.' || p.policyname,
  format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', p.policyname, p.tablename, p.permissive, p.cmd,
    array_to_string(p.roles, ', '),
    case when p.qual is not null then ' USING (' || p.qual || ')' else '' end,
    case when p.with_check is not null then ' WITH CHECK (' || p.with_check || ')' else '' end)
from pg_policies p where p.schemaname='public'
union all
-- 90 permisos de tablas y secuencias (se revoca todo antes, ver encabezado)
select 90, c.relname || ' ' || r.rolname,
  format('GRANT %s ON %s public.%I TO %I;', string_agg(acl.privilege_type, ', ' order by acl.privilege_type),
    case when c.relkind='S' then 'SEQUENCE' else 'TABLE' end, c.relname, r.rolname)
from pg_class c join pg_namespace n on n.oid=c.relnamespace
cross join lateral aclexplode(c.relacl) acl join pg_roles r on r.oid=acl.grantee
where n.nspname='public' and c.relkind in ('r','S') and r.rolname in ('anon','authenticated','service_role')
group by c.relname, c.relkind, r.rolname
union all
-- 91 permisos por columna
select 91, c.relname || '.' || a.attname || ' ' || r.rolname,
  format('GRANT %s (%I) ON TABLE public.%I TO %I;', acl.privilege_type, a.attname, c.relname, r.rolname)
from tbl c join pg_attribute a on a.attrelid=c.oid and a.attnum>0 and not a.attisdropped and a.attacl is not null
cross join lateral aclexplode(a.attacl) acl join pg_roles r on r.oid=acl.grantee
where r.rolname in ('anon','authenticated','service_role')
union all
-- 95 EXECUTE de funciones
select 95, f.proname || '(' || f.args || ') ' || coalesce(r.rolname,'PUBLIC'),
  format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', f.proname, f.args, coalesce(quote_ident(r.rolname),'PUBLIC'))
from fn f join pg_proc p on p.oid=f.oid
cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) acl
left join pg_roles r on r.oid=acl.grantee
where acl.privilege_type='EXECUTE' and (acl.grantee=0 or r.rolname in ('anon','authenticated','service_role'))
union all
-- 97 políticas de storage
select 97, p.policyname,
  format('CREATE POLICY %I ON storage.objects AS %s FOR %s TO %s%s%s;', p.policyname, p.permissive, p.cmd,
    array_to_string(p.roles, ', '),
    case when p.qual is not null then ' USING (' || p.qual || ')' else '' end,
    case when p.with_check is not null then ' WITH CHECK (' || p.with_check || ')' else '' end)
from pg_policies p where p.schemaname='storage' and p.tablename='objects'
union all
select 96, b.id, format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;',
  b.id, b.name, b.public, coalesce(b.file_size_limit::text,'NULL'), coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]','NULL'))
from storage.buckets b
order by 1, 2;
